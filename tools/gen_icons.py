#!/usr/bin/env python3
# Generates crates/reflux/src/icons.rs: every Phosphor icon the Fluxer web app imports, in the
# regular, bold and fill weights, from the @phosphor-icons/core npm package.
# usage: gen_icons.py <fluxer_app/src> <phosphor/package/assets>
import pathlib, re, sys

src, assets = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
root = pathlib.Path(__file__).resolve().parent.parent
names = set()
for f in src.rglob("*.ts*"):
    for m in re.finditer(r"import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*'@phosphor-icons/react[^']*'", f.read_text()):
        for n in m.group(1).split(","):
            n = n.strip().split(" as ")[0].strip()
            if n and n[0].isupper() and not n.startswith("type ") and n not in ("IconProps", "Icon", "IconWeight", "IconContext"):
                names.add(n[:-4] if n.endswith("Icon") else n)


def kebab(n):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])|(?<=[a-zA-Z])(?=[0-9])", "-", n).lower()


out = ["// Generated by tools/gen_icons.py from @phosphor-icons/core (MIT). Do not edit.",
       "#![allow(dead_code)]", "use rune::Icon;", ""]
missing = []
for n in sorted(names):
    k = kebab(n)
    for weight, suffix in (("regular", ""), ("bold", "_BOLD"), ("fill", "_FILL")):
        p = assets / weight / (k + ("" if weight == "regular" else "-" + weight) + ".svg")
        if not p.exists():
            missing.append(str(p.name))
            continue
        svg = p.read_text()
        body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1).strip()
        ident = re.sub(r"[^A-Z0-9]", "_", k.upper()) + suffix
        out.append(f'pub static {ident}: Icon = Icon {{ name: "{k}{suffix.lower()}", view: 256.0, body: r#"{body}"# }};')
(root / "crates/reflux/src/icons.rs").write_text("\n".join(out) + "\n")
print(len(names), "icons;", "missing:", missing)
