#!/usr/bin/env python3
# Generates crates/reflux/src/theme/palette.rs from the computed CSS variables
# captured from the Fluxer web app (assets/theme/{dark,light,coal}.json).
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
themes = {t: json.load(open(root / f"assets/theme/{t}.json")) for t in ("dark", "light", "coal")}


def parse(c):
    m = re.match(r"rgba?\(([\d.]+), ([\d.]+), ([\d.]+)(?:, ([\d.]+))?\)", c)
    if m:
        r, g, b = (float(m.group(i)) / 255 for i in (1, 2, 3))
        return r, g, b, float(m.group(4) or 1)
    m = re.match(r"color\(srgb ([\d.e-]+) ([\d.e-]+) ([\d.e-]+)(?: / ([\d.]+))?\)", c)
    if m:
        return float(m.group(1)), float(m.group(2)), float(m.group(3)), float(m.group(4) or 1)
    m = re.match(r"oklab\(([\d.e-]+) ([\d.e-]+) ([\d.e-]+)(?: / ([\d.]+))?\)", c)
    if m:
        L, A, B = (float(m.group(i)) for i in (1, 2, 3))
        l_, m_, s_ = L + 0.3963377774 * A + 0.2158037573 * B, L - 0.1055613458 * A - 0.0638541728 * B, L - 0.0894841775 * A - 1.2914855480 * B
        l3, m3, s3 = l_ ** 3, m_ ** 3, s_ ** 3
        lin = (4.0767416621 * l3 - 3.3077115913 * m3 + 0.2309699292 * s3,
               -1.2684380046 * l3 + 2.6097574011 * m3 - 0.3413193965 * s3,
               -0.0041960863 * l3 - 0.7034186147 * m3 + 1.7076147010 * s3)
        enc = [min(1, max(0, 12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055)) for x in lin]
        return (*enc, float(m.group(4) or 1))
    raise ValueError(c)


def ident(n):
    s = n[2:].replace("-", "_")
    return "_" + s if s[0].isdigit() else s


names = sorted(set.intersection(*(set(t["col"]) for t in themes.values())))
lens = sorted(themes["dark"]["len"])
out = ["// Generated by tools/gen_theme.py from assets/theme/*.json. Do not edit.",
       "#![allow(dead_code, clippy::all)]", "use rune::Color;", "",
       "/// Every colour CSS variable of the Fluxer web app, resolved to straight sRGB.",
       "#[derive(Clone, Copy, Debug)]", "pub struct Palette {"]
out += [f"    pub {ident(n)}: Color," for n in names]
out += ["}", ""]


def srgb(v):
    return f"rune::color::srgb_decode({v:.6f})"


for t, data in themes.items():
    out.append(f"pub fn {t}() -> Palette {{")
    out.append("    let c = |r: f32, g: f32, b: f32, a: f32| Color { r: rune::color::srgb_decode(r), g: rune::color::srgb_decode(g), b: rune::color::srgb_decode(b), a };")
    out.append("    Palette {")
    for n in names:
        r, g, b, a = parse(data["col"][n])
        out.append(f"        {ident(n)}: c({float(r):.5f}, {float(g):.5f}, {float(b):.5f}, {float(a):.4f}),")
    out += ["    }", "}", ""]

out.append("/// The CSS variable names, in field order.")
out.append("pub const NAMES: &[&str] = &[" + ", ".join(f'"{n}"' for n in names) + "];")
out.append("")
out.append("impl Palette {")
out.append("    /// The field for a CSS variable name (`--text-link`).")
out.append("    pub fn get_mut(&mut self, name: &str) -> Option<&mut Color> {")
out.append("        Some(match name {")
out += [f'            "{n}" => &mut self.{ident(n)},' for n in names]
out += ["            _ => return None,", "        })", "    }", "}", ""]

out.append("/// Dimension CSS variables of the web app, in CSS pixels (1rem = 16px).")
out.append("pub mod dim {")
for n in lens:
    out.append(f"    pub const {ident(n).upper()}: f32 = {float(themes["dark"]["len"][n]):.4f};")
out.append("}")

(root / "crates/reflux/src/theme").mkdir(parents=True, exist_ok=True)
(root / "crates/reflux/src/theme/palette.rs").write_text("\n".join(out) + "\n")
print(len(names), "colours,", len(lens), "dimensions")
